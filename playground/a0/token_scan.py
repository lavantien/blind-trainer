import json
import sys
from pathlib import Path


def scan_file(path):
    rows = []
    chains = 0
    with path.open(encoding="utf-8", newline="") as fh:
        header = fh.readline().rstrip("\n").split("\t")
        assert header == ["case_key", "alg", "front_json", "source_url", "source_at"], header
        for line in fh:
            line = line.rstrip("\n")
            if not line:
                continue
            cols = line.split("\t")
            assert len(cols) == 5, cols
            alg = cols[1]
            if "->" in alg:
                chains += 1
                alg = alg.split("->")[0]
            rows.append((cols[0], alg))
    tokens = set()
    for _, alg in rows:
        tokens.update(alg.split())
    return rows, tokens, chains


def main():
    packs = Path(sys.argv[1])
    out = Path(sys.argv[2])
    registry = json.loads((packs / "registry.json").read_text(encoding="utf-8"))
    allowed = set("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'()w")
    lines = [
        "# pack token inventory",
        "",
        "Distinct move tokens per pack file, extracted from the alg column of each TSV: everything from the first -> onward is stripped, the remainder is split on whitespace, tokens are reported verbatim. The allowed charset is a..z A..Z 0..9 ' ( ) w, any token holding a character outside it is flagged with the offending characters. Generated by playground/a0/token_scan.py driven by registry.json.",
        "",
        "| file | event | rows | distinct tokens | flagged |",
        "| --- | --- | --- | --- | --- |",
    ]
    sections = []
    for entry in registry:
        path = packs / entry["file"]
        rows, tokens, chains = scan_file(path)
        assert len(rows) == entry["expected_rows"], (entry["file"], len(rows))
        ordered = sorted(tokens)
        flagged = {t: sorted(set(t) - allowed) for t in ordered if set(t) - allowed}
        flag_cell = ", ".join(flagged) if flagged else "none"
        lines.append(f"| {entry['file']} | {entry['event']} | {len(rows)} | {len(ordered)} | {flag_cell} |")
        body = [f"## {entry['file']}", ""]
        body.append(f"Event {entry['event']}, {len(rows)} rows, {len(ordered)} distinct tokens"
                    + (f", {chains} rows carried a -> chain that was stripped." if chains else "."))
        body.append("")
        body.append(" ".join(ordered))
        body.append("")
        if flagged:
            body.append("Tokens outside the allowed charset:")
            body.append("")
            for token, bad in flagged.items():
                body.append(f"- {token} holds {' '.join(bad)}")
            body.append("")
        else:
            body.append("No token holds a character outside the allowed charset.")
            body.append("")
        sections.append("\n".join(body))
    out.write_text("\n".join(lines) + "\n\n" + "\n".join(sections), encoding="utf-8", newline="\n")
    print(f"wrote {out} for {len(registry)} files")


if __name__ == "__main__":
    main()
