import re

PACKS = "../../ref_ground/packs"
FILES = [
    ("cfop_pll.tsv", 21, "https://jperm.net/algs/pll"),
    ("cfop_oll.tsv", 57, "https://jperm.net/algs/oll"),
    ("cfop_f2l.tsv", 164, "https://jperm.net/3x3/cfop/f2l"),
]
TOKEN = re.compile(r"2?(?:[UDLRFB]|[udlrfb]|[MES]|[xyz])(?:2?'?)?")
BT_CORE_CLASSES = {
    "face": set("UDLRFB"),
    "wide": set("udlrfb"),
    "slice": set("MES"),
    "rotation": set("xyz"),
}


def scan_alg(alg):
    toks = []
    for t in alg.split():
        if t.endswith(")"):
            core = t.strip("()")
        else:
            m = re.search(r"\)(\d+)$", t)
            core = t[: m.start()] if m else t
            core = core.lstrip("(")
        if not core:
            continue
        toks.append(core)
    return toks


def classify(tok):
    m = TOKEN.fullmatch(tok)
    if not m:
        return None
    base = re.sub(r"^2?", "", tok)
    base = base[:1]
    for cls, chars in BT_CORE_CLASSES.items():
        if base in chars:
            return cls
    return None


def main():
    lines = ["# cfop pack grammar scope scan", "", "Method mirrors playground/a0/token_scan.py: per TSV row, grouping parentheses and repeat digits are stripped from tokens, then every token must fullmatch the bt-core Alg::parse token grammar 2?(UDLRFB|udlrfb|M|E|S|x|y|z)(2|'|2')? (crates/bt-core/src/alg.rs parse_token). Generated by playground/a8/grammar_scan.py.", ""]
    ok_all = True
    for name, expected, url in FILES:
        raw = open(f"{PACKS}/{name}", encoding="utf-8", newline="").read()
        assert "\r" not in raw
        rows = [l.split("\t") for l in raw.split("\n") if l]
        assert rows[0] == ["case_key", "alg", "front_json", "source_url", "source_at"], rows[0]
        body = rows[1:]
        assert len(body) == expected, (name, len(body), expected)
        keys = [r[0] for r in body]
        assert len(set(keys)) == len(keys), name
        tokens = {}
        bad = []
        classes = set()
        for r in body:
            assert len(r) == 5 and all(r), r
            assert r[3] == url and r[4] == "2026-10-16", r
            assert r[2].startswith("{") and r[2].endswith("}"), r
            for tok in scan_alg(r[1]):
                cls = classify(tok)
                if cls is None:
                    bad.append((r[0], tok))
                else:
                    tokens[tok] = tokens.get(tok, 0) + 1
                    classes.add(cls)
        ok = not bad
        ok_all = ok_all and ok
        lines.append(f"## {name}")
        lines.append("")
        lines.append(f"{len(body)} rows, {len(tokens)} distinct move tokens, all within bt-core grammar: {ok}. Token classes present: {', '.join(sorted(classes))}.")
        lines.append("")
        lines.append(" ".join(sorted(tokens)))
        lines.append("")
        if bad:
            lines.append("VIOLATIONS:")
            lines += [f"- {k}: {t}" for k, t in bad]
            lines.append("")
    open("grammar_scan_report.md", "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("\n".join(lines))
    print("ALL OK" if ok_all else "VIOLATIONS FOUND")


if __name__ == "__main__":
    main()
